const TABLES: Record<UiLang, Record<UiStringKey, string>> = { en: EN, am: AM }

export function isUiStringKey(key: string): key is UiStringKey {
  return Object.hasOwn(EN, key)
}

export function t(lang: string, key: UiStringKey): string {
  const table = TABLES[lang as UiLang] ?? TABLES.en
  return table[key] ?? EN[key]
}

export function resolveUiLang(lang: string | null | undefined): UiLang {
  if (!lang) return 'en'
  const base = lang.toLowerCase().split(/[-_]/)[0]
  return base === 'am' ? 'am' : 'en'
}
