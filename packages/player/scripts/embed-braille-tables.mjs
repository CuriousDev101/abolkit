#!/usr/bin/env node
/**
 * Embed the ethio-g1 Liblouis table closure into a TS module for the GPL companion bundle.
 * Run from packages/player (or via build.mjs).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const root = dirname(fileURLToPath(import.meta.url))
const tablesDir = dirname(require.resolve('liblouis-build/tables/ethio-g1.ctb'))

const NAMES = [
  'ethio-g1.ctb',
  'en-us-g1.ctb',
  'braille-patterns.cti',
  'chardefs.cti',
  'latinLetterDef8Dots.uti',
  'litdigits6Dots.uti',
  'loweredDigits6Dots.uti',
]

const tables = Object.fromEntries(
  NAMES.map((name) => [name, readFileSync(join(tablesDir, name), 'utf8')]),
)

const outDir = join(root, '../src/braille')
mkdirSync(outDir, { recursive: true })
const outFile = join(outDir, 'embedded-tables.ts')
writeFileSync(
  outFile,
  `/* eslint-disable */\n/** Auto-generated by scripts/embed-braille-tables.mjs — do not edit. */\nexport const EMBEDDED_TABLES: Record<string, string> = ${JSON.stringify(tables, null, 2)}\n`,
)
console.log(`wrote ${outFile} (${NAMES.length} tables)`)
